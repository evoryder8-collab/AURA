import { expect, test } from '@playwright/test'
import { freshDemo } from './helpers'

test('a therapist enters name and age, sees her portrait, then signs in with username and password', async ({ page }) => {
  await freshDemo(page)
  await page.getByRole('link', { name: /i’m a therapist/i }).click()
  await page.getByLabel(/name/i).first().fill('Pratana Halstrick')
  await page.getByLabel(/age/i).first().fill('35')
  await page.getByRole('button', { name: 'Continue' }).click()
  await expect(page.getByRole('heading', { name: 'Pratana Halstrick' })).toBeVisible()
  await expect(page.locator('img[src*="portraits/pratana-hero"]')).toBeVisible()
  await page.getByRole('button', { name: 'That’s me' }).click()
  await page.getByLabel(/username or email/i).fill('pratana')
  await page.getByLabel(/^password/i).fill('synthetic-demo')
  await page.getByRole('button', { name: /^sign in/i }).click()
  await expect(page).toHaveURL(/#\/therapist\/today/)
  await expect(page.getByRole('heading', { name: /Pratana/ })).toBeVisible()
})

test('a wrong name and age gives one calm answer, and a wrong username is announced', async ({ page }) => {
  await freshDemo(page)
  await page.getByRole('link', { name: /i’m a therapist/i }).click()
  await page.getByLabel(/name/i).first().fill('Wassana Schlaepfer')
  await page.getByLabel(/age/i).first().fill('54')
  await page.getByRole('button', { name: 'Continue' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByLabel(/age/i).first().fill('55')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'That’s me' }).click()
  await page.getByLabel(/username or email/i).fill('pratana')
  await page.getByLabel(/^password/i).fill('synthetic-demo')
  await page.getByRole('button', { name: /^sign in/i }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Fill demo sign-in' }).click()
  await page.getByRole('button', { name: /^sign in/i }).click()
  await expect(page).toHaveURL(/#\/therapist\/today/)
})

test('a client signs in the same way and lands on home', async ({ page }) => {
  await freshDemo(page)
  await page.getByRole('link', { name: /i’m a client/i }).click()
  await page.getByLabel(/name/i).first().fill('Mira Ellison')
  await page.getByLabel(/age/i).first().fill('34')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'That’s me' }).click()
  await page.getByRole('button', { name: 'Fill demo sign-in' }).click()
  await page.getByRole('button', { name: /^sign in/i }).click()
  await expect(page).toHaveURL(/#\/client\/home/)
  await expect(page.getByRole('heading', { level: 1, name: /, Mira$/ })).toBeVisible()
})
